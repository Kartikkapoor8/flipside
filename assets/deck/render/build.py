def load_brand() -> dict:
    tj = BRAND / "tokens.json"
    if not tj.exists():
        print("  brand/tokens.json not found, using placeholder brand")
        return PLACEHOLDER
    t = json.loads(tj.read_text())
    col = t["color"]
    roles = lambda face: {k: col[face][k]["hex"] for k in ("background", "surface", "text", "muted", "accent")}
    disp = t["type"]["display"]
    text = t["type"]["text"]
    return {
        "audience": roles("audience"), "presenter": roles("presenter"),
        "crease": dict(light=col["crease"]["light"], dark=col["crease"]["dark"]),
        "display": f'"{disp["family"]}", {disp.get("fallback", "serif")}',
        "text": f'-apple-system, "{text["family"]} Text", "{text["family"]} Display", "{text["family"]}", Inter, system-ui, sans-serif',
        "scale": t["type"]["scale_canvas1200"],
        "margin": t["space"]["slideMargin_canvas1200"], "gutter": t["space"]["columnGutter_canvas1200"],
        "radius": t["radius"],
        "source": f'brand/tokens.json v{t.get("version", "?")}',
    }


def font_faces() -> str:
    out = []
    for f in sorted((HERE / "fonts").glob("*.ttf")):
        style = "italic" if "italic" in f.name.lower() else "normal"
        fam = re.sub(r"-.*$", "", f.stem)
        fam = re.sub(r"(?<!^)(?=[A-Z])", " ", fam)  # InstrumentSerif -> Instrument Serif
        b64 = base64.b64encode(f.read_bytes()).decode()
        out.append(f'@font-face{{font-family:"{fam}";font-style:{style};font-weight:400;src:url(data:font/ttf;base64,{b64}) format("truetype")}}')
    return "\n".join(out)



def build_deck(deck, slides_dir, notes_dir, fallback, after_last, live_next=None):
    total = len(deck)
    pngs_1x = []
    for i, s in enumerate(deck, 1):
        name = f"{i:02d}-{s['id']}"
        (HTML_DIR / f"{name}.html").write_text(slide_page(s, i, total))
        out1 = slides_dir / "1200x630" / f"{name}.png"
        render(HTML_DIR / f"{name}.html", out1, SLIDE_W, SLIDE_H, 1)
        pngs_1x.append(out1)
    for i, s in enumerate(deck, 1):
        name = f"{i:02d}-{s['id']}"
        render(HTML_DIR / f"{name}.html", slides_dir / "2400x1260" / f"{name}.png", SLIDE_W, SLIDE_H, 2)
    note_pngs = []
    for i, s in enumerate(deck, 1):
        name = f"{i:02d}-{s['id']}"
        nxt = {"png": pngs_1x[i], "label": f"{i + 1} / {total}  {deck[i]['title']}"} if i < total else after_last
        if live_next and s["layout"] == "live":
            nxt = live_next
        (HTML_DIR / f"notes-{name}.html").write_text(notes_page(s, i, total, nxt, fallback))
        out = notes_dir / "800x600" / f"{name}.png"
        render(HTML_DIR / f"notes-{name}.html", out, NOTE_W, NOTE_H, 1)
        note_pngs.append(out)
    return pngs_1x, note_pngs



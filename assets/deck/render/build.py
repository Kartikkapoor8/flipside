def render(html_path: Path, png_path: Path, w: int, h: int, scale: int = 1, timeout: float = 40) -> None:
    """Screenshot one local HTML file. Chrome does not exit on its own after
    --screenshot on this machine, so poll for a stable PNG and then kill it."""
    png_path.parent.mkdir(parents=True, exist_ok=True)
    if png_path.exists():
        png_path.unlink()
    args = [CHROME, "--headless=new", "--disable-gpu", "--hide-scrollbars", "--no-first-run",
            "--no-default-browser-check", f"--user-data-dir={PROFILE}", f"--window-size={w},{h}",
            f"--force-device-scale-factor={scale}", f"--screenshot={png_path}", f"file://{html_path}"]
    proc = subprocess.Popen(args, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    deadline, last = time.time() + timeout, -1
    while time.time() < deadline:
        if png_path.exists():
            size = png_path.stat().st_size
            if size > 0 and size == last:
                break
            last = size
        time.sleep(0.25)
    subprocess.run(["pkill", "-f", f"user-data-dir={PROFILE}"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    try:
        proc.wait(timeout=5)
    except subprocess.TimeoutExpired:
        proc.kill()
    if not png_path.exists() or png_path.stat().st_size == 0:
        sys.exit(f"render failed: {html_path}")
    print(f"  {png_path.relative_to(DECK)}")


def esc(s: str) -> str:
    return html.escape(s, quote=False)


def page(title: str, css: str, body: str) -> str:
    return f'<!doctype html><html><head><meta charset="utf-8"><title>{esc(title)}</title><style>{FONTS}{BRAND_CSS}{css}</style></head><body>{body}</body></html>'


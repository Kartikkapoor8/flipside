def slide_page(s: dict, idx: int, total: int) -> str:
    layout, title, body, cue = s["layout"], esc(s["title"]), esc(s["body"]), esc(s["cue"])
    crease = '<div class="crease"></div><div class="tab"></div>'
    if layout == "cover":
        if s["title"].strip().lower() == "flipside":
            head = f'<div class="wordmark">{WORDMARK}</div>'
            label = ""
        else:
            long = " long" if len(s["title"]) > 22 else ""
            head = f'<div class="markbox">{MARK}</div><h1 class="title{long}">{title}</h1>'
            label = '<div class="label">Flipside</div>'
        faces = f'<div class="face l lit">{label}<div class="spacer"></div>{head}<p class="body muted">{body}</p></div><div class="face r"></div>'
    elif layout == "statement":
        faces = (f'<div class="face l"><div class="num">{idx:02d}</div></div>'
                 f'<div class="face r lit mid"><p class="statement">{title}</p><p class="body">{body}</p></div>')
    elif layout == "split":
        faces = (f'<div class="face l lit"><div class="label">Public face</div><h2 class="heading">{title}</h2><p class="body">{body}</p></div>'
                 f'<div class="face r lit"><div class="label">Private face</div>'
                 f'<div class="mini"><div class="h"><span>Slide {idx} of {total}</span><b>00:00</b></div>'
                 f'<div class="n"><i style="width:100%"></i><i style="width:76%"></i><i style="width:88%"></i></div>'
                 f'<div class="f"><em>“{cue}”</em><span></span></div></div></div>')
    elif layout == "live":
        faces = (f'<div class="face l lit mid"><p class="statement up">{title}</p><p class="body">{body}</p></div>'
                 f'<div class="face r lit mid"><div class="label" style="margin-bottom:16px">Listening</div>'
                 f'<div class="field">{MICRO}<span>listening for a topic</span><i></i></div>'
                 f'<div class="ghosts"><div>slide 1</div><div>slide 2</div><div>slide 3</div></div></div>')
    elif layout == "listen":
        faces = (f'<div class="face l"><div class="num">{idx:02d}</div></div>'
                 f'<div class="face r lit mid"><p class="statement up">{title}</p><p class="body">{body}</p>'
                 f'<div class="pill"><i></i><span>listening for <em>“{cue}”</em></span></div></div>')
    elif layout == "close":
        crease = '<div class="crease top"></div><div class="crease bot"></div>'
